"""Local desktop launcher: one instance, Waitress, readiness check, browser, clean exit.

The Windows executable bundles this interactive app, not Spark or Java. Its
preprocessed outputs must already have been generated by run_spark.py.
"""

import argparse
import json
import os
import sys
import tempfile
import threading
import time
import urllib.request
import webbrowser
from pathlib import Path
from waitress import create_server
from app import create_app

LOCK_PATH = Path(tempfile.gettempdir()) / 'lumen-ir-launcher.lock'
INFO_PATH = Path(tempfile.gettempdir()) / 'lumen-ir-launcher-port.json'


def acquire_instance_lock():
    """Use an OS-managed lock; it is automatically released after a crash or exit."""
    handle = LOCK_PATH.open('a+b')
    handle.seek(0)
    if not handle.read(1):
        handle.write(b'0')
        handle.flush()
    handle.seek(0)
    try:
        if os.name == 'nt':
            import msvcrt
            msvcrt.locking(handle.fileno(), msvcrt.LK_NBLCK, 1)
        else:
            import fcntl
            fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
        return handle
    except OSError:
        handle.close()
        return None


def ready(url):
    """Verify an actual local application response rather than just an open port."""
    try:
        # A local request must not be routed through any machine-wide HTTP proxy.
        opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
        with opener.open(url + '/api/health', timeout=.5) as response:
            return json.load(response).get('application') == 'lumen-ir'
    except (OSError, ValueError):
        return False


def existing_instance(open_browser):
    """A second launch reopens the existing healthy application instead of duplicating it."""
    for _ in range(30):
        try:
            port = json.loads(INFO_PATH.read_text())['port']
            if not isinstance(port, int) or not 1 <= port <= 65535:
                raise ValueError('Invalid port')
            url = f'http://127.0.0.1:{port}'
            if ready(url):
                print('IR Project is already running at ' + url)
                if open_browser:
                    webbrowser.open(url)
                return
        except (OSError, KeyError, ValueError):
            pass
        time.sleep(.1)
    raise RuntimeError('Another launcher is starting but is not ready. Check its console window.')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--no-browser', action='store_true')
    parser.add_argument('--headless', action='store_true', help='Run until Ctrl+C instead of waiting for Enter')
    parser.add_argument('--port', type=int, default=5000)
    args = parser.parse_args()
    lock = acquire_instance_lock()
    if lock is None:
        existing_instance(not args.no_browser)
        return
    server = None
    try:
        app = create_app()
        try:
            server = create_server(app, host='127.0.0.1', port=args.port)
        except OSError:
            # Let the OS choose a free port when another program owns the preferred port.
            server = create_server(app, host='127.0.0.1', port=0)
        port = int(server.effective_port)
        INFO_PATH.write_text(json.dumps({'port': port}), encoding='utf-8')
        url = f'http://127.0.0.1:{port}'
        thread = threading.Thread(target=server.run, daemon=True)
        thread.start()
        for _ in range(50):
            if ready(url):
                break
            time.sleep(.1)
        else:
            raise RuntimeError('The local server did not become ready.')
        print('IR Project is ready at ' + url, flush=True)
        if not args.no_browser:
            webbrowser.open(url)
        if args.headless:
            while thread.is_alive():
                thread.join(.5)
        else:
            input('Press Enter in this window to close the application.\n')
    except (KeyboardInterrupt, EOFError):
        pass
    finally:
        if server is not None:
            server.close()
        INFO_PATH.unlink(missing_ok=True)
        lock.close()


if __name__ == '__main__':
    try:
        main()
    except Exception as error:
        print(f'Cannot start IR Project: {error}', file=sys.stderr)
        if sys.stdin.isatty():
            input('Press Enter to close.\n')
        sys.exit(1)
